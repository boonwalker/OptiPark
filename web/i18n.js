const LANGS = ['de', 'en', 'es'];
const LANG_NAMES = { de: 'Deutsch', en: 'English', es: 'Español' };

const LANG = (() => {
  try {
    const s = localStorage.getItem('park.lang');
    if (LANGS.includes(s)) return s;
  } catch { /* privat */ }
  const dev = (navigator.language || '').toLowerCase();
  return dev.startsWith('de') ? 'de' : dev.startsWith('es') ? 'es' : 'en';
})();

function setLang(lang) {
  try { localStorage.setItem('park.lang', lang); } catch { /* privat */ }
}

function t(de, params) {
  const dict = LANG === 'en' ? I18N_EN : LANG === 'es' ? I18N_ES : null;
  let s = dict ? (dict[de] ?? de) : de;
  if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? params[k] : m));
  return s;
}

const WD_SHORT = {
  de: ['Mo', 'Di', 'Mi', 'Do', 'Fr', 'Sa', 'So'],
  en: ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'],
  es: ['lun', 'mar', 'mié', 'jue', 'vie', 'sáb', 'dom'],
}[LANG];
const MONTHS_EN = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
const MONTHS_ES = ['ene', 'feb', 'mar', 'abr', 'may', 'jun', 'jul', 'ago', 'sep', 'oct', 'nov', 'dic'];

/** Tag als Wort („morgen“) oder kurz mit Datum („Mo 10.11.“ / „Mon 10 Nov“ / „lun 10 nov“). wd: 0 = Montag. */
function fmtDay(diff, wd, day, month) {
  const word = { 0: 'heute', 1: 'morgen', 2: 'übermorgen' }[diff];
  if (word) return t(word);
  const pad = (n) => String(n).padStart(2, '0');
  if (LANG === 'en') return `${WD_SHORT[wd]} ${day} ${MONTHS_EN[month - 1]}`;
  if (LANG === 'es') return `${WD_SHORT[wd]} ${day} ${MONTHS_ES[month - 1]}`;
  return `${WD_SHORT[wd]} ${pad(day)}.${pad(month)}.`;
}

/** Feste Texte in der HTML-Seite: data-i18n (Inhalt) und data-i18n-aria (aria-label). */
function translateStatic(root = document) {
  document.documentElement.lang = LANG;
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.textContent.trim()); });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => el.setAttribute('aria-label', t(el.getAttribute('aria-label'))));
}

